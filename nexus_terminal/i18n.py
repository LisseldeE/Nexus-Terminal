"""Internationalization module - Chinese/English auto-switch based on system language."""

import locale


def detect_language():
    """Detect system language. Returns 'zh' or 'en'."""
    try:
        lang = locale.getdefaultlocale()[0]
        if lang and lang.startswith('zh'):
            return 'zh'
    except Exception:
        pass
    return 'en'


